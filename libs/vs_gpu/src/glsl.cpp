std::string glsl_double(double x) {
  const auto bits = std::bit_cast<std::uint64_t>(x);
  return fmt::format("packDouble2x32(uvec2(0x{:08x}u, 0x{:08x}u))", static_cast<std::uint32_t>(bits),
                     static_cast<std::uint32_t>(bits >> 32));
}

