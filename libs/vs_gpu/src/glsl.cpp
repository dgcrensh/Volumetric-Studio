// The struts of a unit cell, in vs_proc's order (field.cpp unit_struts()).
struct Strut {
  double a[3], b[3];
};

std::vector<Strut> unit_struts(proc::LatticeCell kind) {
  std::vector<Strut> out;
  const auto add = [&](std::array<double, 3> a, std::array<double, 3> b) {
    out.push_back({{a[0], a[1], a[2]}, {b[0], b[1], b[2]}});
  };
  switch (kind) {
    case proc::LatticeCell::Cubic:
      for (int u = 0; u <= 1; ++u) {
        for (int v = 0; v <= 1; ++v) {
          const double du = static_cast<double>(u), dv = static_cast<double>(v);
          add({0, du, dv}, {1, du, dv});
          add({du, 0, dv}, {du, 1, dv});
          add({du, dv, 0}, {du, dv, 1});
        }
      }
      break;
    case proc::LatticeCell::Bcc:
      add({0, 0, 0}, {1, 1, 1});
      add({1, 0, 0}, {0, 1, 1});
      add({0, 1, 0}, {1, 0, 1});
      add({0, 0, 1}, {1, 1, 0});
      break;
    case proc::LatticeCell::Octet: {
      for (int axis = 0; axis < 3; ++axis) {
        for (int side = 0; side <= 1; ++side) {
          const auto pt = [&](double a, double b) {
            std::array<double, 3> q{};
            const double c = static_cast<double>(side);
            if (axis == 0) q = {c, a, b};
            if (axis == 1) q = {a, c, b};
            if (axis == 2) q = {a, b, c};
            return q;
          };
          add(pt(0, 0), pt(1, 1));
          add(pt(1, 0), pt(0, 1));
        }
      }
      const std::array<double, 3> centres[6] = {{0, 0.5, 0.5}, {1, 0.5, 0.5}, {0.5, 0, 0.5},
                                                {0.5, 1, 0.5}, {0.5, 0.5, 0}, {0.5, 0.5, 1}};
      for (int i = 0; i < 6; ++i) {
        for (int j = i + 1; j < 6; ++j) {
          if (i / 2 == j / 2) continue;
          add(centres[i], centres[j]);
        }
      }
      break;
    }
  }
  return out;
}

std::string strut_table(const char* name, proc::LatticeCell kind) {
  const auto struts = unit_struts(kind);
  std::string s = fmt::format("const int {}_N = {};\nconst dvec3 {}[{}] = dvec3[](", name, struts.size(), name,
                              2 * struts.size());
  for (std::size_t i = 0; i < struts.size(); ++i) {
    const auto& st = struts[i];
    s += fmt::format("{}dvec3({:.1f}lf, {:.1f}lf, {:.1f}lf), dvec3({:.1f}lf, {:.1f}lf, {:.1f}lf)", i == 0 ? "" : ", ", st.a[0], st.a[1],
                     st.a[2], st.b[0], st.b[1], st.b[2]);
  }
  return s + ");\n";
}

std::string make_prelude() {
  std::string s = R"(#version 430
// Generated by vs_gpu (glsl.cpp): vs_proc's field arithmetic, operation for
// operation. Every double is `precise`, so nothing is fused into an fma.
#define P precise
layout(local_size_x = 64) in;
layout(std430, binding = 0) readonly buffer DB { double D[]; };
layout(std430, binding = 1) readonly buffer UB { uint U[]; };
layout(std430, binding = 2) writeonly buffer OB { float O[]; };
uniform uint nx;
uniform uint ny;
uniform uint k0;
uniform uint count;

double next_up(double c) { uvec2 b = unpackDouble2x32(c); b.x += 1u; if (b.x == 0u) b.y += 1u; return packDouble2x32(b); }
double next_down(double c) { uvec2 b = unpackDouble2x32(c); if (b.x == 0u) b.y -= 1u; b.x -= 1u; return packDouble2x32(b); }
// The correctly rounded square root: the hardware's, then its neighbours
// checked against the exact residual x - c*c.
double sqrt_rn(double x) {
  P double c = sqrt(x);
  if (!(x > 0.0lf) || isinf(x)) return c;
  for (int it = 0; it < 3; ++it) {
    P double up = next_up(c);
    P double u = up - c;
    P double d = fma(-c, c, x);
    P double cu = c * u;
    if (d > cu) { c = up; continue; }
    P double dn = next_down(c);
    P double ul = c - dn;
    P double cul = c * ul;
    if (d <= -cul) { c = dn; continue; }
    break;
  }
  return c;
}
// std::min, std::max and std::clamp as the C++ library writes them.
double mn(double a, double b) { return (b < a) ? b : a; }
double mx(double a, double b) { return (a < b) ? b : a; }
double cl(double v, double lo, double hi) { return (v < lo) ? lo : ((hi < v) ? hi : v); }
double dot3(dvec3 a, dvec3 b) { P double r = a.x * b.x + a.y * b.y + a.z * b.z; return r; }
double len3(dvec3 v) { return sqrt_rn(dot3(v, v)); }
dvec3 sub3(dvec3 a, dvec3 b) { P dvec3 r = dvec3(a.x - b.x, a.y - b.y, a.z - b.z); return r; }
dvec3 add3(dvec3 a, dvec3 b) { P dvec3 r = dvec3(a.x + b.x, a.y + b.y, a.z + b.z); return r; }
dvec3 mul3(dvec3 a, double s) { P dvec3 r = dvec3(a.x * s, a.y * s, a.z * s); return r; }
double nan_d() { return packDouble2x32(uvec2(0u, 0x7ff80000u)); }
double inf_d() { return packDouble2x32(uvec2(0u, 0x7ff00000u)); }

)";
  // sin_det / cos_det (field.cpp), constants by their bits.
  s += fmt::format(
      "double kernel_sin(double x) {{\n"
      "  P double z = x * x;\n"
      "  P double r = x + x * z * ({} + z * ({} + z * ({} + z * ({} + z * ({} + z * {})))));\n"
      "  return r;\n}}\n",
      glsl_double(-1.66666666666666324348e-01), glsl_double(8.33333333332248946124e-03),
      glsl_double(-1.98412698298579493134e-04), glsl_double(2.75573137070700676789e-06),
      glsl_double(-2.50507602534068634195e-08), glsl_double(1.58969099521155010221e-10));
  s += fmt::format(
      "double kernel_cos(double x) {{\n"
      "  P double z = x * x;\n"
      "  P double r = 1.0lf - 0.5lf * z + z * z * ({} + z * ({} + z * ({} + z * ({} + z * ({} + z * {})))));\n"
      "  return r;\n}}\n",
      glsl_double(4.16666666666666019037e-02), glsl_double(-1.38888888888741095749e-03),
      glsl_double(2.48015872894767294178e-05), glsl_double(-2.75573143513906633035e-07),
      glsl_double(2.08757232129817482790e-09), glsl_double(-1.13596475577881948265e-11));
  s += fmt::format(
      "double reduce_q(double x, out int quadrant) {{\n"
      "  P double k = floor(x * {} + 0.5lf);\n"
      "  P double r = ((x - k * {}) - k * {}) - k * {};\n"
      "  P double m = k - 4.0lf * floor(k * 0.25lf);\n"
      "  quadrant = int(m);\n"
      "  return r;\n}}\n",
      glsl_double(6.36619772367581382433e-01), glsl_double(1.57079632673412561417e+00),
      glsl_double(6.07710050630396597660e-11), glsl_double(2.02226624871116645580e-21));
  s += R"(
double sin_det(double x) {
  if (isinf(x) || isnan(x)) return nan_d();
  int q; P double r = reduce_q(x, q);
  if (q == 0) return kernel_sin(r);
  if (q == 1) return kernel_cos(r);
  if (q == 2) return -kernel_sin(r);
  return -kernel_cos(r);
}
double cos_det(double x) {
  if (isinf(x) || isnan(x)) return nan_d();
  int q; P double r = reduce_q(x, q);
  if (q == 0) return kernel_cos(r);
  if (q == 1) return -kernel_sin(r);
  if (q == 2) return -kernel_cos(r);
  return kernel_sin(r);
}
double smooth_min(double a, double b, double radius) {
  if (!(radius > 0.0lf)) return mn(a, b);
  P double h = cl(0.5lf + 0.5lf * (b - a) / radius, 0.0lf, 1.0lf);
  P double r = b + (a - b) * h - radius * h * (1.0lf - h);
  return r;
}
double smooth_max(double a, double b, double radius) { return -smooth_min(-a, -b, radius); }
double box_sdf(dvec3 p, dvec3 c, dvec3 h) {
  P dvec3 q = dvec3(abs(p.x - c.x) - h.x, abs(p.y - c.y) - h.y, abs(p.z - c.z) - h.z);
  P dvec3 o = dvec3(mx(q.x, 0.0lf), mx(q.y, 0.0lf), mx(q.z, 0.0lf));
  P double r = len3(o) + mn(mx(q.x, mx(q.y, q.z)), 0.0lf);
  return r;
}
double segment_distance(dvec3 p, dvec3 a, dvec3 b) {
  P dvec3 ab = sub3(b, a);
  P dvec3 ap = sub3(p, a);
  P double t = cl(dot3(ap, ab) / dot3(ab, ab), 0.0lf, 1.0lf);
  return len3(sub3(ap, mul3(ab, t)));
}
)";
  s += strut_table("CUBIC", proc::LatticeCell::Cubic);
  s += strut_table("BCC", proc::LatticeCell::Bcc);
  s += strut_table("OCTET", proc::LatticeCell::Octet);
  s += fmt::format("const double TWO_PI = {};\n", glsl_double(2.0 * std::numbers::pi));
  s += fmt::format("const double TPMS_FLOOR = {};\n", glsl_double(0.1));
  s += R"(
double lattice_distance(int kind, dvec3 p, dvec3 origin, double cell) {
  P dvec3 u = mul3(sub3(p, origin), 1.0lf / cell);
  P dvec3 q = dvec3(u.x - floor(u.x), u.y - floor(u.y), u.z - floor(u.z));
  P double best = inf_d();
  if (kind == 0) {
    for (int i = 0; i < CUBIC_N; ++i) best = mn(best, segment_distance(q, CUBIC[2 * i], CUBIC[2 * i + 1]));
  } else if (kind == 1) {
    for (int i = 0; i < BCC_N; ++i) best = mn(best, segment_distance(q, BCC[2 * i], BCC[2 * i + 1]));
  } else {
    for (int i = 0; i < OCTET_N; ++i) best = mn(best, segment_distance(q, OCTET[2 * i], OCTET[2 * i + 1]));
  }
  P double r = best * cell;
  return r;
}
double tpms_distance(int kind, dvec3 p, dvec3 origin, double cell) {
  P double w = TWO_PI / cell;
  P dvec3 x = mul3(sub3(p, origin), w);
  P double sx = sin_det(x.x); P double cx = cos_det(x.x);
  P double sy = sin_det(x.y); P double cy = cos_det(x.y);
  P double sz = sin_det(x.z); P double cz = cos_det(x.z);
  P double f;
  P dvec3 g;
  if (kind == 0) {
    f = sx * cy + sy * cz + sz * cx;
    g = dvec3(cx * cy - sz * sx, cy * cz - sx * sy, cz * cx - sy * sz);
  } else if (kind == 1) {
    f = cx + cy + cz;
    g = dvec3(-sx, -sy, -sz);
  } else {
    f = sx * sy * sz + sx * cy * cz + cx * sy * cz + cx * cy * sz;
    g = dvec3(cx * sy * sz + cx * cy * cz - sx * sy * cz - sx * cy * sz,
              sx * cy * sz - sx * sy * cz + cx * cy * cz - cx * sy * sz,
              sx * sy * cz - sx * cy * sz - cx * sy * sz + cx * cy * cz);
  }
  P double grad = mx(len3(g), TPMS_FLOOR);
  P double r = abs(f) / (w * grad);
  return r;
}

// --- meshes (vs_proc TriangleDistance) ------------------------------------------
// Mesh info at U[s .. s + 8): D offsets of positions, vertex normals,
// triangle normals (12 per triangle), node boxes (6 per node); U offsets of
// triangle vertices (3 each), nodes (first, count, left) and leaf order;
// flags (1 closed, 2 has nodes).
dvec3 dv(uint o) { return dvec3(D[o], D[o + 1u], D[o + 2u]); }
double box_dist2(uint s, uint node, dvec3 p) {
  uint o = U[s + 4u] + 6u * node;
  P double d = 0.0lf;
  P double lo; P double hi; P double q;
  lo = D[o]; hi = D[o + 3u]; q = p.x;
  if (q < lo) { d += (lo - q) * (lo - q); } else if (q > hi) { d += (q - hi) * (q - hi); }
  lo = D[o + 1u]; hi = D[o + 4u]; q = p.y;
  if (q < lo) { d += (lo - q) * (lo - q); } else if (q > hi) { d += (q - hi) * (q - hi); }
  lo = D[o + 2u]; hi = D[o + 5u]; q = p.z;
  if (q < lo) { d += (lo - q) * (lo - q); } else if (q > hi) { d += (q - hi) * (q - hi); }
  return d;
}
// Ericson 5.1.5, as distance.cpp writes it: the nearest point and feature.
dvec3 closest_on_triangle(dvec3 p, dvec3 a, dvec3 b, dvec3 c, out int feature) {
  P dvec3 ab = sub3(b, a);
  P dvec3 ac = sub3(c, a);
  P dvec3 ap = sub3(p, a);
  P double d1 = dot3(ab, ap);
  P double d2 = dot3(ac, ap);
  if (d1 <= 0.0lf && d2 <= 0.0lf) { feature = 4; return a; }
  P dvec3 bp = sub3(p, b);
  P double d3 = dot3(ab, bp);
  P double d4 = dot3(ac, bp);
  if (d3 >= 0.0lf && d4 <= d3) { feature = 5; return b; }
  P double vc = d1 * d4 - d3 * d2;
  if (vc <= 0.0lf && d1 >= 0.0lf && d3 <= 0.0lf) {
    P double v = d1 / (d1 - d3);
    feature = 1;
    return add3(a, mul3(ab, v));
  }
  P dvec3 cp = sub3(p, c);
  P double d5 = dot3(ab, cp);
  P double d6 = dot3(ac, cp);
  if (d6 >= 0.0lf && d5 <= d6) { feature = 6; return c; }
  P double vb = d5 * d2 - d1 * d6;
  if (vb <= 0.0lf && d2 >= 0.0lf && d6 <= 0.0lf) {
    P double w = d2 / (d2 - d6);
    feature = 3;
    return add3(a, mul3(ac, w));
  }
  P double va = d3 * d6 - d5 * d4;
  if (va <= 0.0lf && (d4 - d3) >= 0.0lf && (d5 - d6) >= 0.0lf) {
    P double w = (d4 - d3) / ((d4 - d3) + (d5 - d6));
    feature = 2;
    return add3(b, mul3(sub3(c, b), w));
  }
  P double denom = 1.0lf / (va + vb + vc);
  P double v = vb * denom;
  P double w = vc * denom;
  feature = 0;
  return add3(add3(a, mul3(ab, v)), mul3(ac, w));
}
// The nearest triangle, visiting nodes in the order the CPU's recursion
// does: the nearer child first, the other only while it can still win.
double mesh_nearest(uint s, dvec3 p, out dvec3 point, out uint tri, out int feature) {
  P double best = inf_d();
  point = dvec3(0.0lf);
  tri = 0u;
  feature = 0;
  if ((U[s + 7u] & 2u) == 0u) return best;
  uint stack_node[64];
  double stack_bound[64];
  int top = 0;
  stack_node[0] = 0u;
  stack_bound[0] = -inf_d();
  top = 1;
  while (top > 0) {
    --top;
    uint node = stack_node[top];
    P double bound = stack_bound[top];
    if (!(bound < best)) continue;
    uint nu = U[s + 5u] + 3u * node;
    uint first = U[nu];
    uint count = U[nu + 1u];
    uint left = U[nu + 2u];
    if (count > 0u) {
      for (uint i = first; i < first + count; ++i) {
        uint t = U[U[s + 6u] + i];
        uint tv = U[s + 3u] + 3u * t;
        dvec3 a = dv(U[s] + 3u * U[tv]);
        dvec3 b = dv(U[s] + 3u * U[tv + 1u]);
        dvec3 c = dv(U[s] + 3u * U[tv + 2u]);
        int f;
        P dvec3 q = closest_on_triangle(p, a, b, c, f);
        P dvec3 dq = sub3(p, q);
        P double d = dot3(dq, dq);
        if (d < best) { best = d; point = q; tri = t; feature = f; }
      }
      continue;
    }
    P double dl = box_dist2(s, left, p);
    P double dr = box_dist2(s, left + 1u, p);
    uint near_node = dl <= dr ? left : left + 1u;
    uint far_node = dl <= dr ? left + 1u : left;
    stack_node[top] = far_node; stack_bound[top] = mx(dl, dr); ++top;
    stack_node[top] = near_node; stack_bound[top] = mn(dl, dr); ++top;
  }
  return best;
}
double mesh_unsigned(uint s, dvec3 p) {
  dvec3 q; uint t; int f;
  return sqrt_rn(mesh_nearest(s, p, q, t, f));
}
double mesh_signed(uint s, dvec3 p) {
  dvec3 q; uint t; int f;
  P double d = sqrt_rn(mesh_nearest(s, p, q, t, f));
  if ((U[s + 7u] & 3u) != 3u) return d;
  uint to = U[s + 2u] + 12u * t;
  dvec3 normal;
  if (f == 0) normal = dv(to);
  else if (f <= 3) normal = dv(to + 3u * uint(f));
  else normal = dv(U[s + 1u] + 3u * U[U[s + 3u] + 3u * t + uint(f - 4)]);
  return dot3(sub3(p, q), normal) < 0.0lf ? -d : d;
}
)";
  return s;
}

// The generator: one function per distinct node, children first.
class Translator {
 public:
  FieldProgram run(const FieldExpr& root) {
    out_.d = {0, 0, 0, 0};  // grid origin and cell, filled per sample
    visit(root);
    // U: N, offsets, counts, mesh infos, then the mesh uints.
    const auto n = static_cast<std::uint32_t>(nodes_.size());
    out_.u.assign(1 + 2 * static_cast<std::size_t>(n) + 8 * meshes_.size(), 0);
    out_.u[0] = n;
    for (std::uint32_t j = 0; j < n; ++j) {
      const FieldExpr* e = nodes_[j];
      out_.u[1 + j] = static_cast<std::uint32_t>(out_.d.size());
      out_.u[1 + n + j] = static_cast<std::uint32_t>(e->numbers().size());
      out_.d.insert(out_.d.end(), e->numbers().begin(), e->numbers().end());
    }
    for (std::size_t m = 0; m < meshes_.size(); ++m) upload(m, 1 + 2 * n + 8 * static_cast<std::uint32_t>(m));
    std::string& s = out_.source;
    s = prelude();
    s += code_;
    s += fmt::format(R"(
void main() {{
  uint g = gl_GlobalInvocationID.x;
  if (g >= count) return;
  uint i = g % nx;
  uint j = (g / nx) % ny;
  uint k = k0 + g / (nx * ny);
  P dvec3 p = dvec3(D[0] + double(i) * D[3], D[1] + double(j) * D[3], D[2] + double(k) * D[3]);
  O[g] = float(f{}(p));
}}
)",
                     index_.at(&root));
    return std::move(out_);
  }

 private:
  // Node j's k-th number.
  static std::string num(std::size_t j, std::size_t k) {
    return fmt::format("D[U[{}u] + {}u]", 1 + j, k);
  }
  std::string vec(std::size_t j, std::size_t k) {
    return fmt::format("dvec3({}, {}, {})", num(j, k), num(j, k + 1), num(j, k + 2));
  }

  std::size_t visit(const FieldExpr& e) {
    if (const auto it = index_.find(&e); it != index_.end()) return it->second;
    std::vector<std::size_t> kids;
    for (const auto& c : e.children()) kids.push_back(visit(*c));
    const std::size_t j = nodes_.size();
    nodes_.push_back(&e);
    index_.emplace(&e, j);
    const auto c = [&](std::size_t i, const char* at = "p") { return fmt::format("f{}({})", kids.at(i), at); };
    std::string body;
    switch (e.op()) {
      case FieldOp::Constant: body = fmt::format("r = {};", num(j, 0)); break;
      case FieldOp::Sphere: body = fmt::format("r = len3(sub3(p, {})) - {};", vec(j, 0), num(j, 3)); break;
      case FieldOp::Box: body = fmt::format("r = box_sdf(p, {}, {});", vec(j, 0), vec(j, 3)); break;
      case FieldOp::Cylinder:
        body = fmt::format(
            "P dvec3 axis = {}; P dvec3 d = sub3(p, {}); P double along = dot3(d, axis);\n"
            "  P double radial = len3(sub3(d, mul3(axis, along)));\n"
            "  P double qx = radial - {}; P double qy = abs(along) - {};\n"
            "  P double ox = mx(qx, 0.0lf); P double oy = mx(qy, 0.0lf);\n"
            "  r = sqrt_rn(ox * ox + oy * oy) + mn(mx(qx, qy), 0.0lf);",
            vec(j, 3), vec(j, 0), num(j, 6), num(j, 7));
        break;
      case FieldOp::Plane: body = fmt::format("r = abs(dot3(sub3(p, {}), {}));", vec(j, 0), vec(j, 3)); break;
      case FieldOp::HalfSpace: body = fmt::format("r = dot3(sub3(p, {}), {});", vec(j, 0), vec(j, 3)); break;
      case FieldOp::MeshSigned:
      case FieldOp::MeshUnsigned: {
        const std::size_t slot = mesh_slot(e.mesh());
        // The info base depends on N, known only at the end: a constant
        // patched in by name.
        body = fmt::format("r = {}(MESH{}, p);", e.op() == FieldOp::MeshSigned ? "mesh_signed" : "mesh_unsigned",
                           slot);
        break;
      }
      case FieldOp::Union: body = fmt::format("r = mn({}, {});", c(0), c(1)); break;
      case FieldOp::Intersection: body = fmt::format("r = mx({}, {});", c(0), c(1)); break;
      case FieldOp::Difference: body = fmt::format("r = mx({}, -{});", c(0), c(1)); break;
      case FieldOp::SmoothUnion: body = fmt::format("r = smooth_min({}, {}, {});", c(0), c(1), num(j, 0)); break;
      case FieldOp::SmoothIntersection:
        body = fmt::format("r = smooth_max({}, {}, {});", c(0), c(1), num(j, 0));
        break;
      case FieldOp::SmoothDifference:
        body = fmt::format("r = smooth_max({}, -{}, {});", c(0), c(1), num(j, 0));
        break;
      case FieldOp::Offset: body = fmt::format("r = {} - {};", c(0), num(j, 0)); break;
      case FieldOp::Shell: body = fmt::format("P double d = {}; r = mx(d, -d - {});", c(0), num(j, 0)); break;
      case FieldOp::Negate: body = fmt::format("r = -{};", c(0)); break;
      case FieldOp::Abs: body = fmt::format("r = abs({});", c(0)); break;
      case FieldOp::Add: body = fmt::format("r = {} + {};", c(0), c(1)); break;
      case FieldOp::Multiply: body = fmt::format("r = {} * {};", c(0), c(1)); break;
      case FieldOp::Scale: body = fmt::format("r = {} * {};", c(0), num(j, 0)); break;
      case FieldOp::Clamp: body = fmt::format("r = cl({}, {}, {});", c(0), num(j, 0), num(j, 1)); break;
      case FieldOp::Lattice:
      case FieldOp::Tpms: {
        const std::string thickness =
            e.children().empty() ? num(j, 5) : fmt::format("mx({}, 0.0lf)", c(0));
        body = fmt::format("P double t = {}; P double d = {}(int({}), p, {}, {}); r = d - 0.5lf * t;", thickness,
                           e.op() == FieldOp::Lattice ? "lattice_distance" : "tpms_distance", num(j, 0),
                           vec(j, 2), num(j, 1));
        break;
      }
      case FieldOp::Instances:
        body = fmt::format(
            "P double best = inf_d();\n"
            "  uint copies = (U[{}u + U[0]] - 1u) / 13u;\n"
            "  for (uint c = 0u; c < copies; ++c) {{\n"
            "    uint m = U[{}u] + 1u + 13u * c;\n"
            "    P dvec3 d = dvec3(p.x - D[m + 9u], p.y - D[m + 10u], p.z - D[m + 11u]);\n"
            "    if (D[m + 12u] > 0.0lf && len3(d) - D[m + 12u] >= best) continue;\n"
            "    P dvec3 local = dvec3(D[m] * d.x + D[m + 1u] * d.y + D[m + 2u] * d.z,\n"
            "                          D[m + 3u] * d.x + D[m + 4u] * d.y + D[m + 5u] * d.z,\n"
            "                          D[m + 6u] * d.x + D[m + 7u] * d.y + D[m + 8u] * d.z);\n"
            "    best = mn(best, {});\n"
            "  }}\n"
            "  r = best;",
            1 + j, 1 + j, c(0, "local"));
        break;
    }
    code_ += fmt::format("double f{}(dvec3 p) {{\n  P double r;\n  {}\n  return r;\n}}\n", j, body);
    return j;
  }

  std::size_t mesh_slot(const proc::TriangleDistance* mesh) {
    for (std::size_t i = 0; i < meshes_.size(); ++i) {
      if (meshes_[i] == mesh) return i;
    }
    meshes_.push_back(mesh);
    return meshes_.size() - 1;
  }

  void upload(std::size_t m, std::uint32_t info) {
    const proc::TriangleDistance& t = *meshes_[m];
    auto& d = out_.d;
    auto& u = out_.u;
    const auto put = [&](const core::dvec3& v) {
      d.push_back(v.x);
      d.push_back(v.y);
      d.push_back(v.z);
    };
    u[info + 0] = static_cast<std::uint32_t>(d.size());
    for (const auto& p : t.positions()) put(p);
    u[info + 1] = static_cast<std::uint32_t>(d.size());
    for (const auto& n : t.vertex_normals()) put(n);
    u[info + 2] = static_cast<std::uint32_t>(d.size());
    for (const auto& tri : t.triangles()) {
      put(tri.normal);
      for (const auto& en : tri.edge_normal) put(en);
    }
    u[info + 4] = static_cast<std::uint32_t>(d.size());
    for (const auto& node : t.nodes()) {
      put(node.box.min);
      put(node.box.max);
    }
    u[info + 3] = static_cast<std::uint32_t>(u.size());
    for (const auto& tri : t.triangles()) u.insert(u.end(), {tri.v[0], tri.v[1], tri.v[2]});
    u[info + 5] = static_cast<std::uint32_t>(u.size());
    for (const auto& node : t.nodes()) u.insert(u.end(), {node.first, node.count, node.left});
    u[info + 6] = static_cast<std::uint32_t>(u.size());
    u.insert(u.end(), t.order().begin(), t.order().end());
    u[info + 7] = (t.closed() ? 1u : 0u) | (t.nodes().empty() ? 0u : 2u);
  }

  FieldProgram out_;
  std::string code_;
  std::vector<const FieldExpr*> nodes_;
  std::map<const FieldExpr*, std::size_t> index_;
  std::vector<const proc::TriangleDistance*> meshes_;
};

