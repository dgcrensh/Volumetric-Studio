// GPU meshing (L1b; decision 0019): the boundary clip and the unmerged
// surface net, element for element what vs_proc's CPU code makes.
//
// The clip samples the boundary's signed distance plus the inset with L1's
// field shader (offset(d, -inset) is d + inset exactly) and takes the max
// on the CPU. The unmerged net runs four passes over the grid padded by
// one sample all round, as mesher.cpp's loops do:
//
//   1. per cube: which of its six tetrahedra the surface crosses (a mask);
//   2. per cube, at its first vertex (an exclusive sum of the masks' bit
//      counts in grid order, made on the CPU): each crossed tetrahedron's
//      crossing sum and count, in the CPU's edge order;
//   3. per grid point: how many triangles its crossed edges fan into;
//   4. per grid point, at its first triangle (another exclusive sum): the
//      fans, with the apex chosen by the same areas (sqrt correctly
//      rounded) and comparisons.
//
// Vertex and triangle order is therefore the CPU's, and so is every bit.

